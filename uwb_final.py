# 7. Attention Blocks
# ============================================================
def channel_attention(inputs, ratio=8):
    ch = int(inputs.shape[-1])
    gap = layers.GlobalAveragePooling2D()(inputs)
    fc1 = layers.Dense(ch // ratio, activation="relu")(gap)
    fc2 = layers.Dense(ch, activation="sigmoid")(fc1)
    scale = layers.Reshape((1,1,ch))(fc2)
    return layers.Multiply()([inputs, scale])

def ap_attention_softmax(inputs):
    # (B, 8, W, C) → (B, 8, C)
    squeeze = layers.Lambda(lambda x: tf.reduce_mean(x, axis=2))(inputs)
    score = layers.Dense(1)(squeeze)
    score = layers.Softmax(axis=1)(score)
    score = layers.Reshape((8,1,1))(score)
    return layers.Multiply()([inputs, score])



# ============================================================
# 8. 2D CNN 모델 구성
# ============================================================
inputs = keras.Input(shape=(8,130,1))

# --- Block 1 ---
x1 = layers.Conv2D(32,(3,5),padding="same",activation="swish")(inputs)
x2 = layers.Conv2D(16,(5,9),padding="same",activation="swish")(inputs)
x = layers.Concatenate()([x1,x2])
x = layers.BatchNormalization()(x)

# --- Block 2 (MS)
x1 = layers.Conv2D(64,(3,5),padding="same",activation="swish")(x)
x2 = layers.Conv2D(32,(5,9),padding="same",activation="swish")(x)
x = layers.Concatenate()([x1,x2])
x = layers.BatchNormalization()(x)
x = layers.MaxPooling2D((1,2))(x)

# --- Block 3 (Dilated + Attention)
x = layers.Conv2D(128,(3,3),activation="swish",padding="same")(x)
x = layers.Conv2D(128,(3,3),activation="swish",padding="same",dilation_rate=2)(x)
x = layers.BatchNormalization()(x)

x = channel_attention(x)
x = ap_attention_softmax(x)
x = layers.GlobalAveragePooling2D()(x)

# --- Dense Head + Residual 2 Blocks ---
x = layers.Dense(128,activation="swish")(x)
x = layers.Dropout(0.2)(x)

for _ in range(2):
    res = x
    h = layers.Dense(128,activation="swish")(x)
    h = layers.Dense(128)(h)
    x = layers.Add()([res,h])
    x = layers.Activation("swish")(x)

x = layers.Dense(64,activation="swish")(x)
x = layers.Dropout(0.15)(x)

outputs = layers.Dense(2)(x)

model = keras.Model(inputs, outputs)
model.compile(optimizer=keras.optimizers.Adam(3e-4), loss="mse")


# ============================================================
# 9. 콜백
# ============================================================
es = EarlyStopping(monitor="val_loss", patience=15, min_delta=1e-4,
                   restore_best_weights=True, verbose=1)
lr = ReduceLROnPlateau(monitor="val_loss", factor=0.5,
                       patience=6, min_lr=1e-5, verbose=1)


# ============================================================
# 10. 학습
# ============================================================
history = model.fit(
    X_tr, y_tr, epochs=120, batch_size=64,
    validation_data=(X_val,y_val),
    callbacks=[es,lr], verbose=1
)


