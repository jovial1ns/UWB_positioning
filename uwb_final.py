import numpy as np
import pandas as pd
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers, regularizers
import matplotlib.pyplot as plt

from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau

from google.colab import drive
drive.mount('/content/drive')

tf.random.set_seed(42)
np.random.seed(42)


# ============================================================
# 1. 데이터 로드
# ============================================================
train_df = pd.read_csv("/content/drive/MyDrive/Colab Notebooks/Toa_sort.csv", header=None)
test_df  = pd.read_csv("/content/drive/MyDrive/Colab Notebooks/Toa_test_sort.csv", header=None)

train_arr = train_df.values
test_arr  = test_df.values

num_anchor = 8
n_cols = train_arr.shape[1]
n_cir = n_cols - 4   # CIR length 128

N_train_row = len(train_arr)
N_test_row  = len(test_arr)

assert N_train_row % num_anchor == 0
assert N_test_row  % num_anchor == 0

N_train = N_train_row // num_anchor
N_test  = N_test_row  // num_anchor

train_group = train_arr.reshape(N_train, num_anchor, n_cols)
test_group  = test_arr.reshape(N_test, num_anchor, n_cols)


# ============================================================
# 2. 라벨
# ============================================================
y_train_raw = train_group[:, 0, 0:2]
y_test_raw  = test_group[:, 0, 0:2]


# ============================================================
# 3. ToA / CIR / Energy
# ============================================================
ToA_train_row = train_arr[:, 3].reshape(-1,1)
ToA_test_row  = test_arr[:, 3].reshape(-1,1)

CIR_train_row = train_arr[:, 4:]
CIR_test_row  = test_arr[:, 4:]

CIR_E_train = np.sum(CIR_train_row**2, axis=1, keepdims=True)
CIR_E_test  = np.sum(CIR_test_row**2, axis=1, keepdims=True)


# ============================================================
# 4. Scaling
# ============================================================
scaler_cir = StandardScaler()
CIR_train_scaled_row = scaler_cir.fit_transform(np.log1p(CIR_train_row))
CIR_test_scaled_row  = scaler_cir.transform(np.log1p(CIR_test_row))

scaler_toa = StandardScaler()
ToA_train_scaled = scaler_toa.fit_transform(ToA_train_row)
ToA_test_scaled  = scaler_toa.transform(ToA_test_row)

scaler_E = StandardScaler()
CIR_E_train_scaled = scaler_E.fit_transform(np.log1p(CIR_E_train))
CIR_E_test_scaled  = scaler_E.transform(np.log1p(CIR_E_test))

scaler_y = StandardScaler()
y_train = scaler_y.fit_transform(y_train_raw)
y_test  = scaler_y.transform(y_test_raw)


# ============================================================
# 5. 8 비콘 묶기 → (8,130) → Flatten → (1040,1)
# ============================================================
ToA_train_group = ToA_train_scaled.reshape(N_train, num_anchor, 1)
ToA_test_group  = ToA_test_scaled.reshape(N_test, num_anchor, 1)

CIR_train_group = CIR_train_scaled_row.reshape(N_train, num_anchor, n_cir)
CIR_test_group  = CIR_test_scaled_row.reshape(N_test, num_anchor, n_cir)

CIR_E_train_group = CIR_E_train_scaled.reshape(N_train, num_anchor, 1)
CIR_E_test_group  = CIR_E_test_scaled.reshape(N_test, num_anchor, 1)

# shape = (N, 8, 130)
X_train_group = np.concatenate([ToA_train_group, CIR_train_group, CIR_E_train_group], axis=2)
X_test_group  = np.concatenate([ToA_test_group, CIR_test_group, CIR_E_test_group], axis=2)

# Flatten → (N, 8*130 = 1040, 1)
X_train_cnn = X_train_group.reshape(N_train, -1, 1).astype("float32")
X_test_cnn  = X_test_group.reshape(N_test,  -1, 1).astype("float32")

print("1D CNN Input Shape:", X_train_cnn.shape)


# ============================================================
# 6. Train/Val Split
# ============================================================
X_tr, X_val, y_tr, y_val = train_test_split(
    X_train_cnn, y_train, test_size=0.2, shuffle=True, random_state=42
)


# ============================================================
# 7. 1D CNN 모델 구성
# ============================================================
inputs = keras.Input(shape=(X_train_cnn.shape[1], 1))

x = layers.Conv1D(64, 5, padding="same", activation="relu")(inputs)
x = layers.Conv1D(64, 5, padding="same", activation="relu")(x)
x = layers.MaxPooling1D(2)(x)

x = layers.Conv1D(128, 5, padding="same", activation="relu")(x)
x = layers.Conv1D(128, 5, padding="same", activation="relu")(x)
x = layers.MaxPooling1D(2)(x)

x = layers.Flatten()(x)
x = layers.Dense(256, activation="relu")(x)
x = layers.Dropout(0.2)(x)

x = layers.Dense(128, activation="relu")(x)
x = layers.Dropout(0.15)(x)

outputs = layers.Dense(2)(x)

model = keras.Model(inputs, outputs)
model.compile(optimizer=keras.optimizers.Adam(3e-4), loss="mse")

model.summary()


# ============================================================
# 8. 콜백
# ============================================================
es = EarlyStopping(monitor="val_loss", patience=12, restore_best_weights=True, verbose=1)
lr = ReduceLROnPlateau(monitor="val_loss", patience=6, factor=0.5, min_lr=1e-5, verbose=1)


# ============================================================
# 9. 학습
# ============================================================
history = model.fit(
    X_tr, y_tr, epochs=120, batch_size=64,
    validation_data=(X_val, y_val),
    callbacks=[es, lr], verbose=1
)


# ============================================================
# 10. 평가 + 저장
# ============================================================
def compute_errors(pred, real):
    return np.linalg.norm(pred - real, axis=1)

pred_tp = scaler_y.inverse_transform(model.predict(X_test_cnn))
err_tp = compute_errors(pred_tp, y_test_raw)

np.save("error_tp_1dcnn.npy", err_tp)
np.save("y_test_raw.npy", y_test_raw)
model.save("cnn_1d_final.h5")


# ============================================================
# 11. 성능 지표 출력
