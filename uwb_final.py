# =========================================
# 10) Train 세트 예측 및 오차
# =========================================
y_train_pred_scaled = model.predict(X_train, verbose=0)
y_train_pred = scaler_y.inverse_transform(y_train_pred_scaled)

x_hat_tr = y_train_pred[:, 0]
