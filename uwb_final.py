scaler_toa = StandardScaler()
ToA_train_scaled = scaler_toa.fit_transform(ToA_train_row)
ToA_test_scaled  = scaler_toa.transform(ToA_test_row)

scaler_E = StandardScaler()
CIR_E_train_scaled = scaler_E.fit_transform(np.log1p(CIR_E_train))
CIR_E_test_scaled  = scaler_E.transform(np.log1p(CIR_E_test))

