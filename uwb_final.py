print("Train raw shape:", train_df.shape)
print("Test  raw shape:", test_df.shape)

# 열 의미 가정:
# 0: x, 1: y, 2: anchor_id(1~8), 3: ToA, 4~: CIR(128개)
num_anchor = 8

# =========================================
# 2) 8개씩 묶을 수 있는지 확인 + anchor 패턴 검사
# =========================================
train_arr = train_df.values
test_arr  = test_df.values

N_train_row, n_cols = train_arr.shape
N_test_row,  _      = test_arr.shape

assert N_train_row % num_anchor == 0, "train 행 수가 8의 배수가 아님"
assert N_test_row  % num_anchor == 0, "test 행 수가 8의 배수가 아님"

N_train_sample = N_train_row // num_anchor   # 위치 개수
N_test_sample  = N_test_row  // num_anchor

# (N_pos, 8, n_cols)로 묶기
train_group = train_arr.reshape(N_train_sample, num_anchor, n_cols)
test_group  = test_arr.reshape(N_test_sample,  num_anchor, n_cols)

print("Train grouped:", train_group.shape)  # (N_pos, 8, n_cols)
print("Test  grouped:", test_group.shape)

# anchor id가 각 세트마다 [1,2,3,4,5,6,7,8]인지 검사
train_anchor = train_group[:, :, 2]   # shape: (N_train_sample, 8)
test_anchor  = test_group[:, :, 2]

expected = np.arange(1, num_anchor+1).reshape(1, num_anchor)  # (1,8)

assert np.all(train_anchor == expected), "train에서 anchor 순서가 1~8이 아닌 세트가 있음"
assert np.all(test_anchor  == expected), "test에서 anchor 순서가 1~8이 아닌 세트가 있음"

# =========================================
# 3) 라벨 y: 8행 → 1위치 라벨로 축소
#    (각 위치에서 첫 번째 행의 (x,y)를 사용)
# =========================================
y_train_row = train_arr[:, 0:2]   # (N_train_row, 2)
y_test_row  = test_arr[:, 0:2]

y_train_group = y_train_row.reshape(N_train_sample, num_anchor, 2)
y_test_group  = y_test_row.reshape(N_test_sample,  num_anchor, 2)

y_train = y_train_group[:, 0, :]   # (N_train_sample, 2)
y_test  = y_test_group[:, 0, :]    # (N_test_sample,  2)

print("y_train shape:", y_train.shape)
print("y_test  shape:", y_test.shape)

# =========================================
# 4) 입력 feature: ToA + CIR (행 기준)
# =========================================
ToA_train_row = train_arr[:, 3].reshape(-1, 1)   # (N_train_row, 1)
ToA_test_row  = test_arr[:, 3].reshape(-1, 1)

CIR_train_row = train_arr[:, 4:]                 # (N_train_row, 128)
CIR_test_row  = test_arr[:, 4:]

n_cir = CIR_train_row.shape[1]
print("CIR length:", n_cir)

# =========================================
